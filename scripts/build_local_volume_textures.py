"""Package the 3D artwork for browsers that open the catalog through file://."""

import base64
from io import BytesIO
import json
from pathlib import Path

from PIL import Image, ImageOps


WEB = Path(__file__).resolve().parents[1] / "web"
MOLD_TEXTURES = {
    "cera-brillo": (
        "frente.jpg", "canto-cera.jpg", "canto-ingredientes.jpg",
        "crema-foto.jpg",
    ),
    "cera-fibra": ("frente.jpg", "canto-nombre.jpg", "canto-ingredientes.jpg"),
    "pasta": ("frente.jpg",),
    "pomada": ("frente.jpg",),
}


def texture_files():
    assets = WEB / "assets"
    models = WEB / "productos_3d"
    yield from (assets / name for name in ("isotipo-white.png", "logotipo-white.png"))
    yield from assets.glob("lid-*.png")
    yield from assets.glob("strip-*.jpg")
    yield from models.glob("*/texturas/*-3d.webp")
    for model, files in MOLD_TEXTURES.items():
        yield from (models / model / "texturas" / name for name in files)


def encoded_texture(path):
    if path.suffix == ".webp":
        data = path.read_bytes()
    else:
        with Image.open(path) as source:
            mode = "RGBA" if "A" in source.getbands() or "transparency" in source.info else "RGB"
            image = ImageOps.exif_transpose(source).convert(mode)
        image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
        buffer = BytesIO()
        image.save(buffer, "WEBP", quality=93, method=5)
        data = buffer.getvalue()
    return "data:image/webp;base64," + base64.b64encode(data).decode("ascii")


def main():
    textures = {path.relative_to(WEB).as_posix(): encoded_texture(path) for path in sorted(texture_files())}
    bundle = WEB / "js" / "volume-textures.local.js"
    bundle.write_text(
        "// Generated by scripts/build_local_volume_textures.py.\n"
        + "window.VOLUME_LOCAL_TEXTURES = "
        + json.dumps(textures, indent=2)
        + ";\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
